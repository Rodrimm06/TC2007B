CREATE TABLE estancia(
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) UNIQUE NOT NULL,
    ubicacion VARCHAR(255) UNIQUE NOT NULL
); --ESTANCIAS INFANTILES

CREATE TABLE sala(
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estancia_id INT NOT NULL,
    nombre VARCHAR(255) NOT NULL,
    min_personal INT NOT NULL,
    FOREIGN KEY (estancia_id) REFERENCES estancia(id)
);--CADA CUARTO O SALA DE LAS ESTANCIAS

CREATE TABLE usuario(
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estancia_id INT NOT NULL,
    auth_uid VARCHAR(255),
    nombre VARCHAR(255) NOT NULL,
    correo VARCHAR(255) NOT NULL UNIQUE,
    rol VARCHAR(255) NOT NULL,
    FOREIGN KEY (estancia_id) REFERENCES estancia(id)
);--COORDINADORES Y/O DIRECCION

CREATE TABLE personal(
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estancia_id INT NOT NULL,
    nombre VARCHAR(255) NOT NULL UNIQUE,
    tipo VARCHAR(255) NOT NULL,
    estatus VARCHAR(255),
    fecha_alta DATE,
    fecha_baja DATE,
    FOREIGN KEY (estancia_id) REFERENCES estancia(id)
);--TODO EL PERSONAL QUE SE VA A ESTAR ADMINISTRANDO

CREATE TABLE turno(
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hora_inicio TIME NOT NULL,
    hora_fin TIME NOT NULL,
    nombre VARCHAR(255) NOT NULL
);--TURNOS DE LOS TRABAJADORES

CREATE TABLE tarea(
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_responsable INT NOT NULL,
    id_estancia INT NOT NULL,
    nombre VARCHAR(255) NOT NULL,
    fecha DATE,
    hora_inicio TIME,
    hora_fin TIME,
    FOREIGN KEY (id_responsable) REFERENCES personal(id),
    FOREIGN KEY (id_estancia) REFERENCES estancia(id)
);--TAREAS (RF EXTRA)

CREATE TABLE tarea_item(
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_tarea INT NOT NULL,
    descripcion VARCHAR(255) NOT NULL,
    completado BOOLEAN DEFAULT FALSE,
    fecha_completado DATE,
    FOREIGN KEY (id_tarea) REFERENCES tarea(id)
);--CADA ITEM DE LAS TAREAS (RF EXTRA)

CREATE TABLE incidencia(
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_personal INT NOT NULL,
    id_encargado INT NOT NULL,
    tipo VARCHAR(255),
    motivo VARCHAR(255),
    fecha DATE,
    fecha_registro TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (id_personal) REFERENCES personal(id),
    FOREIGN KEY (id_encargado) REFERENCES usuario(id)
);--REGISTRO DE INCIDENCIAS

CREATE TABLE horario(
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_personal INT NOT NULL,
    id_turno INT NOT NULL,
    id_sala INT NOT NULL,
    fecha DATE,
    FOREIGN KEY (id_personal) REFERENCES personal(id),
    FOREIGN KEY (id_turno) REFERENCES turno(id),
    FOREIGN KEY (id_sala) REFERENCES sala(id)
);--HORARIO DE CADA TRABAJADOR

CREATE TABLE asistencia(
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_personal INT NOT NULL,
    id_encargado INT NOT NULL,
    id_turno INT NOT NULL,
    id_sala INT NOT NULL,
    fecha DATE,
    hora_entrada TIME,
    hora_salida TIME,
    estatus VARCHAR(255),
    fecha_registro TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (id_personal) REFERENCES personal(id),
    FOREIGN KEY (id_encargado) REFERENCES usuario(id),
    FOREIGN KEY (id_turno) REFERENCES turno(id),
    FOREIGN KEY (id_sala) REFERENCES sala(id)
);--PARA TOMAR ASISTENCIA DE CADA TRABAJADOR